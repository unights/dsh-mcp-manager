#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = createRequire(import.meta.url).resolve('esbuild/bin/esbuild');
mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
function bundle(args) {
  // Inherit stdio so the CLI also works inside hosts that restrict named pipes.
  const windows = process.platform === 'win32';
  const result = spawnSync(windows ? process.execPath : cli, windows ? [cli, ...args] : args,
    { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const shared = ['--bundle', '--target=es2022', '--legal-comments=none'];
// The source is ordinary ESM. Only the final artifact uses DSH's loader envelope.
bundle(['src/client/index.ts', ...shared, '--platform=browser', '--format=cjs', '--external:react',
  '--loader:.css=text', '--outfile=dist/client.js',
  '--banner:js=// Generated by scripts/build.mjs — do not edit.\nwindow.__ModuleLoader__.load({ id: "dsh-mcp-servers", factory(require) {\nconst module = { exports: {} };',
  '--footer:js=\nreturn module.exports;\n} });']);
bundle(['src/host/index.ts', ...shared, '--platform=node', '--format=esm', '--packages=external',
  '--outfile=dist/host.js', '--banner:js=// Generated by scripts/build.mjs — do not edit.']);
